CREATE DATABASE IF NOT EXISTS AcaBiblioteca
 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE AcaBiblioteca;

CREATE TABLE IF NOT EXISTS Autores (
 IdAutor INT AUTO_INCREMENT PRIMARY KEY,
 Nombre VARCHAR(100) NOT NULL,
 Apellido VARCHAR(100) NOT NULL,
 INDEX idx_autor_nombre (Nombre, Apellido)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Editoriales (
 IdEditorial INT AUTO_INCREMENT PRIMARY KEY,
 Nombre VARCHAR(160) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Usuarios (
 IdUsuario INT AUTO_INCREMENT PRIMARY KEY,
 Nombre VARCHAR(100) NOT NULL,
 Apellido VARCHAR(100) NOT NULL,
 Documento VARCHAR(40) NOT NULL UNIQUE,
 Correo VARCHAR(180) NOT NULL UNIQUE,
 Telefono VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Libros (
 ISBN VARCHAR(20) PRIMARY KEY,
 Titulo VARCHAR(240) NOT NULL,
 IdAutor INT NOT NULL,
 IdEditorial INT NOT NULL,
 Categoria VARCHAR(100) NOT NULL,
 Anio SMALLINT NOT NULL,
 Existencias INT NOT NULL DEFAULT 0,
 CONSTRAINT chk_libros_existencias CHECK (Existencias >= 0),
 CONSTRAINT fk_libros_autores FOREIGN KEY (IdAutor) REFERENCES Autores(IdAutor)
  ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_libros_editoriales FOREIGN KEY (IdEditorial) REFERENCES Editoriales(IdEditorial)
  ON UPDATE CASCADE ON DELETE RESTRICT,
 INDEX idx_libros_titulo (Titulo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Prestamos (
 IdPrestamo INT AUTO_INCREMENT PRIMARY KEY,
 ISBN VARCHAR(20) NOT NULL,
 IdUsuario INT NOT NULL,
 FechaPrestamo DATE NOT NULL,
 FechaVencimiento DATE NOT NULL,
 FechaDevolucion DATE NULL,
 Estado ENUM('Prestado','Devuelto') NOT NULL DEFAULT 'Prestado',
 CONSTRAINT fk_prestamos_libros FOREIGN KEY (ISBN) REFERENCES Libros(ISBN)
  ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_prestamos_usuarios FOREIGN KEY (IdUsuario) REFERENCES Usuarios(IdUsuario)
  ON UPDATE CASCADE ON DELETE RESTRICT,
 INDEX idx_prestamos_estado (Estado),
 INDEX idx_prestamos_usuario (IdUsuario)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
